// IAPWS R9-97, Eq. 1. Pure water at 20 C, density 998.207 kg/m^3.
// n is relative to vacuum; divide by the ambient-air index for ray interfaces.
inline double waterIndex(double nm, double kelvin = 293.15, double density = 998.207) {
    const double r = density / 1000, t = kelvin / 273.15, l = nm / 589, l2 = l * l;
    const double a = r * (.244257733 + .00974634476 * r - .00373234996 * t + .000268678472 * l2 * t +
                          .00158920570 / l2 + .00245934259 / (l2 - .2292020 * .2292020) +
                          .900704920 / (l2 - 5.432937 * 5.432937) - .0166626219 * r * r);
    return std::sqrt((1 + 2 * a) / (1 - a));
}
