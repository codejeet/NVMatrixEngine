inline float waterAbsorption(float nm) {
    auto first = std::begin(waterAbsorptionSamples), last = std::end(waterAbsorptionSamples);
    auto hi = std::lower_bound(first, last, nm, [](auto p, float x) { return p.first < x; });
    if (hi == first)
        return float(hi->second);
    if (hi == last)
        return float((last - 1)->second);
    auto lo = hi - 1;
    return float(lo->second + (hi->second - lo->second) * (nm - lo->first) / (hi->first - lo->first));
}
inline float waterHeight(float x, float z, bool flat = false) {
    // Frozen capillary/gravity-wave snapshot, not an animated fluid simulation.
    return 1.10f +
           (flat ? 0.f
                 : .065f * std::sin(3.7f * x + 2.9f * z) + .035f * std::sin(-4.3f * x + 1.7f * z + .8f));
}
